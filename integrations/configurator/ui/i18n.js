/** Englischer Oberflaechentext zum deutschen Schluessel (mit {platzhaltern}). */
export function tr(text, params) {
  let out = EN[text] ?? text;
  if (params) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return out;
}
